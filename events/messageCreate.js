// ============================================================
// EVENT: messageCreate — vouch commands and auto-moderation
// ============================================================
const { runAutoMod } = require('../handlers/autoModHandler');
const config = require('../config');
const { CV2_FLAGS } = require('../utils/embedBuilder');
const {
    ContainerBuilder, TextDisplayBuilder, SeparatorBuilder, SeparatorSpacingSize,
    PermissionFlagsBits,
} = require('discord.js');

function money(value) { return `₹${Number(value).toFixed(2)}`; }
function escapeMentions(value) { return String(value ?? '').replace(/@/g, '@\u200b'); }
function cleanProduct(value) { return String(value ?? '').replace(/\s+/g, ' ').trim(); }

async function handlePlusRep(message) {
    const channelId = config.VOUCH?.CHANNEL_ID;
    if (!channelId || message.channelId !== channelId) return false;
    const content = message.content.trim();
    if (!/^\+rep(?:\s|$)/i.test(content)) return false;

    if (!message.member?.permissions?.has(PermissionFlagsBits.ManageGuild)) {
        await message.reply('Only admins with Manage Server permission can publish purchase vouches.').catch(() => {});
        return true;
    }

    const match = content.match(/^\+rep\s+(\d{17,20})\s+LEGIT PURCHASED\s+(\d+)X\s+(.+?)\s+FOR\s+₹?([\d,]+(?:\.\d{1,2})?)\s+\[([^\]]+)\]$/i);
    if (!match) {
        await message.reply('Vouch format is invalid. Use the exact `+rep` command generated by `/vouch-req`.').catch(() => {});
        return true;
    }

    const [, userId, qtyRaw, productRaw, priceRaw, paymentRaw] = match;
    const quantity = Number(qtyRaw);
    const productName = cleanProduct(productRaw);
    const totalPrice = Number(priceRaw.replace(/,/g, ''));
    const paymentMethod = paymentRaw.trim();
    const { Vouch, VouchRequest } = require('../utils/database');

    const request = await VouchRequest.findOne({
        where: { guildId: message.guildId, channelId, userId, productName, quantity, totalPrice, paymentMethod, status: 'pending' },
        order: [['createdAt', 'ASC']],
    });
    if (!request) {
        await message.reply('No matching pending `/vouch-req` was found. Create a fresh request and paste its generated command.').catch(() => {});
        return true;
    }

    if (request.transactionId) {
        const duplicate = await Vouch.findOne({ where: { guildId: request.guildId, userId: request.userId, transactionId: request.transactionId } });
        if (duplicate) {
            await request.update({ status: 'duplicate' });
            await message.reply('This transaction ID already has a recorded vouch. No duplicate was added.').catch(() => {});
            await message.delete().catch(() => {});
            return true;
        }
    }

    await Vouch.create({
        guildId: request.guildId, userId: request.userId, adminId: request.adminId,
        productName: request.productName, quantity: request.quantity,
        unitPrice: request.unitPrice, totalPrice: request.totalPrice,
        paymentMethod: request.paymentMethod || 'Not specified', transactionId: request.transactionId,
    });
    await request.update({ status: 'confirmed', messageId: message.id });
    await message.delete().catch(() => {});

    const tickId = config.VOUCH?.TICK_EMOJI_ID;
    const tick = tickId ? `<a:tick:${tickId}>` : '✅';
    const card = new ContainerBuilder()
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(`## ${tick} LEGIT PURCHASED`))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(
            `**Customer**\n<@${request.userId}>\n\n` +
            `**Product**\n${escapeMentions(request.productName)}\n\n` +
            `**Quantity**\n×${request.quantity}\n\n` +
            `**Total Price**\n${money(request.totalPrice)} (${money(request.unitPrice)} each)\n\n` +
            `**Payment Method**\n${escapeMentions(request.paymentMethod || 'Not specified')}\n\n` +
            `**Transaction ID**\n${escapeMentions(request.transactionId || 'Not provided')}`
        ))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(
            `-# Vouch added to <@${request.userId}>'s purchase history • Recorded by <@${message.author.id}> • GOJO`
        ));
    await message.channel.send({ components: [card], flags: CV2_FLAGS, allowedMentions: { users: [] } });
    return true;
}

async function handleMinusRep(message) {
    if (!/^-rep(?:\s|$)/i.test(message.content.trim())) return false;
    const channelId = config.VOUCH?.CHANNEL_ID;
    if (!channelId || message.channelId !== channelId) {
        if (channelId) await message.reply(`Negative feedback can only be recorded in <#${channelId}>.`).catch(() => {});
        return true;
    }
    if (!message.member?.permissions?.has(PermissionFlagsBits.ManageGuild)) {
        await message.reply('Only admins with Manage Server permission can record negative feedback.').catch(() => {});
        return true;
    }
    const idMatch = message.content.trim().match(/\b\d{17,20}\b/);
    const target = message.mentions.users.first() || (idMatch && await message.client.users.fetch(idMatch[0]).catch(() => null));
    const reason = message.content.trim().replace(/^-rep\s*/i, '').replace(/<@!?\d{17,20}>|\b\d{17,20}\b/, '').trim();
    if (!target || !reason) {
        await message.reply('Usage: `-rep @member brief factual reason`').catch(() => {});
        return true;
    }
    const { VouchFeedback } = require('../utils/database');
    await VouchFeedback.create({ guildId: message.guildId, userId: target.id, adminId: message.author.id, reason: reason.slice(0, 1000).replace(/@/g, '@\u200b') });
    const card = new ContainerBuilder()
        .addTextDisplayComponents(new TextDisplayBuilder().setContent('## ⚠️ Admin-Recorded Negative Feedback'))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(`**Member**\n<@${target.id}> · ID: ${target.id}\n\n**Feedback**\n${escapeMentions(reason)}`))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(`-# Recorded by <@${message.author.id}> • GOJO feedback record`));
    await message.channel.send({ components: [card], flags: CV2_FLAGS, allowedMentions: { users: [] } }).catch(() => {});
    await message.delete().catch(() => {});
    return true;
}

async function handlePrefixLookup(message) {
    if (!/^-p(?:\s|$)/i.test(message.content.trim())) return false;
    const targetMatch = message.content.trim().match(/\b\d{17,20}\b/);
    const target = message.mentions.users.first() || (targetMatch && await message.client.users.fetch(targetMatch[0]).catch(() => null));
    if (!target) {
        await message.reply('Usage: `-p @member` or `-p DISCORD_USER_ID`').catch(() => {});
        return true;
    }
    const { Vouch, VouchFeedback } = require('../utils/database');
    const records = await Vouch.findAll({ where: { guildId: message.guildId, userId: target.id }, order: [['createdAt', 'DESC']] }).catch(() => []);
    const feedback = await VouchFeedback.findAll({ where: { guildId: message.guildId, userId: target.id }, order: [['createdAt', 'DESC']] }).catch(() => []);
    const totalQty = records.reduce((sum, row) => sum + Number(row.quantity), 0);
    const totalSpent = records.reduce((sum, row) => sum + Number(row.totalPrice), 0);
    const byProduct = new Map();
    for (const row of records) {
        const item = byProduct.get(row.productName) || { qty: 0, amount: 0 };
        item.qty += Number(row.quantity); item.amount += Number(row.totalPrice); byProduct.set(row.productName, item);
    }
    const lines = [...byProduct.entries()].slice(0, 15).map(([name, item]) => `• **${escapeMentions(name)}** — Qty ×${item.qty} · Total ${money(item.amount)}`);
    const card = new ContainerBuilder()
        .addTextDisplayComponents(new TextDisplayBuilder().setContent('## 🧾 Member Vouch History'))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(`**Member**\n<@${target.id}> · ID: ${target.id}\n\n**Confirmed vouches**\n${records.length}\n\n**Products purchased**\n×${totalQty}\n\n**Total recorded spend**\n${money(totalSpent)}\n\n**Negative feedback records**\n${feedback.length}`))
        .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small).setDivider(true))
        .addTextDisplayComponents(new TextDisplayBuilder().setContent(`### Product breakdown\n${lines.length ? lines.join('\n') : 'No confirmed vouches found.'}\n\n-# GOJO • Purchase records are based on admin requests published in the vouch channel.`));
    await message.reply({ components: [card], flags: CV2_FLAGS, allowedMentions: { users: [], repliedUser: false } }).catch(() => {});
    return true;
}

module.exports = {
    name: 'messageCreate',
    async execute(message, client) {
        if (message.author?.bot || !message.guild) return;
        try {
            if (await handlePlusRep(message)) return;
            if (await handleMinusRep(message)) return;
            if (await handlePrefixLookup(message)) return;
            await runAutoMod(message);
        } catch (error) {
            console.error('[Vouch/messageCreate] Error:', error);
            if (message.content.trim().startsWith('+rep')) {
                await message.reply('Could not process this vouch due to a bot/database error. Please check the bot logs.').catch(() => {});
            }
        }
    },
};
